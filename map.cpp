void resetItens(int map[MAP_HEIGHT][MAP_WIDTH]) {
    for (int i = 0; i < MAP_HEIGHT; ++i)
        for (int j = 0; j < MAP_WIDTH; ++j)
            if (map[i][j] == 2 || map[i][j] == 3 || map[i][j] == 4 || map[i][j] == 6)
                map[i][j] = 0;
}

void updateVisibility(bool visible[MAP_HEIGHT][MAP_WIDTH], Player player) {
    int visionRadius, x = player.x, y = player.y;
    if(player.hasTorch) {
        visionRadius = 2;
    } else {
        visionRadius = 1;
    }
    for (int dx = -visionRadius; dx <= visionRadius; ++dx)
        for (int dy = -visionRadius; dy <= visionRadius; ++dy) {
            int nx = x + dx, ny = y + dy;
            if (nx >= 0 && ny >= 0 && nx < MAP_HEIGHT && ny < MAP_WIDTH)
                visible[nx][ny] = true;
        }
}

